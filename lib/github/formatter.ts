import { sanitizeText } from "@/lib/sanitizer";

export interface FormatIssueInput {
  failureSignature: {
    id: string;
    signatureHash: string;
    errorType?: string | null;
    normalizedError: string;
    occurrenceCount: number;
    firstSeenAt: Date | string;
    lastSeenAt: Date | string;
  };
  sampleDetail?: {
    sanitizedErrorMessage: string;
    sanitizedStackTrace?: string | null;
    testResult?: {
      testTitle: string;
      specFile: string;
      role?: string | null;
    } | null;
  } | null;
  cmsBaseUrl?: string;
}

export interface FormattedIssue {
  title: string;
  body: string;
  labels: string[];
}

/**
 * Formats a standardized, sanitized GitHub Issue for automated QA defect tracking.
 */
export function formatGitHubIssue(input: FormatIssueInput): FormattedIssue {
  const { failureSignature, sampleDetail, cmsBaseUrl } = input;
  const testTitle = sampleDetail?.testResult?.testTitle || failureSignature.errorType || "Automated Test Failure";
  const specFile = sampleDetail?.testResult?.specFile || "Unknown Specification";
  const role = sampleDetail?.testResult?.role || "default";

  // Diagnostic error
  const rawErrorMessage = sampleDetail?.sanitizedErrorMessage || failureSignature.normalizedError;
  const sanitizedErrorMessage = sanitizeText(rawErrorMessage);
  const firstErrorLine = sanitizedErrorMessage.split("\n")[0]?.trim() || "Test failed during execution";

  // Build Title: "[Bug] <Test Title>: <Summary>" (Truncated to max 150 chars)
  const rawTitle = `[Bug] ${testTitle}: ${firstErrorLine}`;
  const sanitizedTitle = sanitizeText(rawTitle);
  const title = sanitizedTitle.length > 150 ? `${sanitizedTitle.slice(0, 147)}...` : sanitizedTitle;

  // Timestamps
  const firstSeenStr = new Date(failureSignature.firstSeenAt).toISOString();
  const lastSeenStr = new Date(failureSignature.lastSeenAt).toISOString();

  // CMS Link
  const baseUrl = cmsBaseUrl || process.env.NEXT_PUBLIC_APP_URL || "http://localhost:3000";
  const failureUrl = `${baseUrl.replace(/\/$/, "")}/failures/${failureSignature.id}`;

  // Stack trace section
  const stackTrace = sampleDetail?.sanitizedStackTrace
    ? sanitizeText(sampleDetail.sanitizedStackTrace)
    : null;

  const stackTraceBlock = stackTrace
    ? `\n<details>\n<summary><b>Stack Trace</b> (click to expand)</summary>\n\n\`\`\`text\n${stackTrace}\n\`\`\`\n</details>\n`
    : "";

  const roleRow = role !== "default" ? `| **Role** | \`${role}\` |\n` : "";

  const body = `## Automated QA Defect Report

### Overview
| Attribute | Details |
| :--- | :--- |
| **Spec File** | \`${specFile}\` |
| **Test Title** | ${testTitle} |
${roleRow}| **Occurrences** | ${failureSignature.occurrenceCount} |
| **First Seen** | ${firstSeenStr} |
| **Last Seen** | ${lastSeenStr} |
| **Signature Hash** | \`${failureSignature.signatureHash}\` |

### Error Diagnostic
\`\`\`text
${sanitizedErrorMessage}
\`\`\`
${stackTraceBlock}
### CMS Diagnostics
- **View Failure in CMS:** [${failureSignature.signatureHash.slice(0, 12)}](${failureUrl})
- **Signature Hash:** \`${failureSignature.signatureHash}\`

---
*Auto-generated by QA-Platform CMS. Please do not modify the Signature Hash to maintain deduplication tracking.*
`.trim();

  const labels = ["automated-defect", "qa-failure"];
  if (role && role !== "default") {
    labels.push(`role:${role.toLowerCase()}`);
  }

  return {
    title,
    body: sanitizeText(body),
    labels,
  };
}
